import 'package:my_flutter_app/services/parking_month_statement.dart';

/// Month end test data: a car on a customer's bill and the customer's card,
/// built the way the statement builds them, with only what a test names.
ParkingMonthBill testBill({
  String id = 'car-1',
  String vehicle = '2014 Honda Accord',
  String vin = '1HGCR2F3XEA004821',
  String trackingCode = 'PK-AAAAAA',
  int dueCents = 37200,
  int priorUnpaidCents = 0,
  String periodFrom = '2026-10-01',
  bool recordable = true,
}) => ParkingMonthBill(
  id: id,
  monthKey: '2026-10',
  periodFrom: periodFrom,
  periodTo: '2026-10-31',
  days: 31,
  dayRateCents: 1200,
  monthCents: dueCents,
  monthPaidCents: 0,
  monthUnpaidCents: dueCents,
  priorUnpaidCents: priorUnpaidCents,
  dueCents: dueCents,
  owes: dueCents > 0,
  stillParked: true,
  partialMonth: false,
  customerName: '',
  customerPhone: '',
  customerEmail: '',
  vehicle: vehicle,
  vinNumber: vin,
  trackingCode: trackingCode,
  recordable: recordable,
);

ParkingMonthCustomer testCustomer({
  String key = 'phone:2015550142',
  String name = 'Customer A',
  String phone = '+12015550142',
  List<ParkingMonthBill>? cars,
  List<ParkingCarriedCar> olderCars = const [],
  List<ParkingMonthActivity> activities = const [],
  int monthPaidCents = 0,
  int priorUnpaidCents = 0,
  int dueCents = 37200,
  bool? owes,
  bool paid = false,
  String forStaffId = '',
  int expenseCreditCents = 0,
  int? cashHeldCents,
  int? statementOwesCents,
  String statementStaffId = '',
  String includedInStatementOf = '',
  List<String> linkedStaffIds = const [],
}) {
  final bills = cars ?? [testBill(dueCents: dueCents)];
  return ParkingMonthCustomer(
    key: key,
    monthKey: '2026-10',
    customerName: name,
    customerPhone: phone,
    customerEmail: '',
    cars: bills,
    registeredTo: [for (final _ in bills) ''],
    activities: activities,
    olderActivities: const [],
    activityRegisteredTo: [for (final _ in activities) ''],
    olderRegisteredTo: const [],
    monthCents: dueCents + monthPaidCents,
    monthPaidCents: monthPaidCents,
    monthUnpaidCents: dueCents,
    priorUnpaidCents: priorUnpaidCents,
    dueCents: dueCents,
    owes: owes ?? dueCents > 0,
    paid: paid,
    paidVia: const [],
    partialMonth: false,
    forStaffId: forStaffId,
    expenseCreditCents: expenseCreditCents,
    olderCars: olderCars,
    olderCarsRegisteredTo: [for (final _ in olderCars) ''],
    linkedStaffIds: linkedStaffIds,
    cashHeldCents: cashHeldCents,
    statementOwesCents: statementOwesCents,
    statementStaffId: statementStaffId,
    includedInStatementOf: includedInStatementOf,
  );
}
